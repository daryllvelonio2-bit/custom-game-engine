/// Atlas texture dimensions.
pub const ATLAS_WIDTH: u32 = COLS * CELL_W;
pub const ATLAS_HEIGHT: u32 = ROWS * CELL_H;

/// Build the font atlas image: white glyphs on a transparent background.
pub fn build_atlas() -> RgbaImage {
    let mut img = RgbaImage::new(ATLAS_WIDTH, ATLAS_HEIGHT);
    let white = Rgba([255, 255, 255, 255]);
    for index in 0..GLYPH_COUNT {
        let gx = (index as u32 % COLS) * CELL_W;
        let gy = (index as u32 / COLS) * CELL_H;
        let glyph = GLYPHS[index];
        for col in 0..GLYPH_WIDTH as usize {
            let bits = glyph[col];
            for row in 0..GLYPH_HEIGHT as usize {
                if bits & (1 << row) != 0 {
                    img.put_pixel(gx + col as u32, gy + row as u32, white);
                }
            }
        }
    }
    img
}

/// UV rectangle for a character, in normalized atlas coordinates.
pub fn char_uv(ch: char) -> [f32; 4] {
    let code = ch as u32;
    let index = if code < FIRST_CHAR as u32 || code > 127 {
        0
    } else {
        (code - FIRST_CHAR as u32) as usize
    };
    let gx = (index as u32 % COLS) * CELL_W;
    let gy = (index as u32 / COLS) * CELL_H;
    let u0 = gx as f32 / ATLAS_WIDTH as f32;
    let v0 = gy as f32 / ATLAS_HEIGHT as f32;
    let u1 = (gx + GLYPH_WIDTH) as f32 / ATLAS_WIDTH as f32;
    let v1 = (gy + GLYPH_HEIGHT) as f32 / ATLAS_HEIGHT as f32;
    [u0, v0, u1, v1]
}

/// Pixel width of a string rendered at `scale`.
pub fn text_width(text: &str, scale: f32) -> f32 {
    text.chars().count() as f32 * (CELL_W as f32 * scale)
}

/// Pixel height of a line rendered at `scale`.
pub fn text_height(scale: f32) -> f32 {
    CELL_H as f32 * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn atlas_has_expected_size() {
        let img = build_atlas();
        assert_eq!(img.width(), ATLAS_WIDTH);
        assert_eq!(img.height(), ATLAS_HEIGHT);
    }

    #[test]
    fn space_is_blank_but_a_is_not() {
        let img = build_atlas();
        let space = char_uv(' ');
        let a = char_uv('A');
        assert!(space[2] > space[0]);
        assert!(a[2] > a[0]);
        assert_eq!(img.get_pixel(0, 0).0[3], 0);
    }

    #[test]
    fn text_width_scales() {
        assert!(text_width("abc", 2.0) > text_width("abc", 1.0));
    }
}
